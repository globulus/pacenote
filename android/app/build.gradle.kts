// Debug builds bake in the service's address and token (written by scripts/setup.sh),
// so they work without pairing. Don't share a debug APK. Release builds carry
// neither: they pair by scanning the QR code from scripts/pair.sh.
val pacenoteHome = File(System.getenv("PACENOTE_HOME") ?: "${System.getProperty("user.home")}/.pacenote")
fun homeFile(name: String): String = File(pacenoteHome, name).takeIf { it.isFile }?.readText()?.trim().orEmpty()
val serviceToken: String = homeFile("token")
val serviceUrl: String = (findProperty("pacenote.serviceUrl") as String?) ?: homeFile("url")
val serviceHost: String = runCatching { URI(serviceUrl).host }.getOrNull().orEmpty()

// Release signing: a keystore kept outside the repo (see the README).
val signingFile = File(System.getenv("PACENOTE_SIGNING") ?: "${System.getProperty("user.home")}/.pacenote-release/signing.properties")
val signing = Properties().apply { if (signingFile.isFile) signingFile.inputStream().use { load(it) } }

/**
 * The app may use plain HTTP only to Tailscale hosts (Tailscale encrypts the
 * link): MagicDNS names, plus, for debug builds, the service's own address.
 */
abstract class NetworkConfigTask : DefaultTask() {
    @get:Input abstract val host: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val domains = listOf(host.get(), "127.0.0.1", "localhost").filter { it.isNotEmpty() }.distinct()
            .joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
        val file = outputDir.get().file("xml/network_security_config.xml").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by app/build.gradle.kts. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |        <domain includeSubdomains="true">ts.net</domain>
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin()
        )
    }
}

android {
    namespace = "com.theglobulus.pacenote"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.theglobulus.pacenote"
        // remoteMessaging foreground services need API 34.
        minSdk = 34
        targetSdk = 36
        // Minutes since 1970, so every build installs over the last one (in-app updates need that).
        versionCode = (System.currentTimeMillis() / 60_000).toInt()
        versionName = "0.3.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("String", "DEFAULT_SERVICE_URL", "\"$serviceUrl\"")
        buildConfigField("String", "DEFAULT_TOKEN", "\"$serviceToken\"")
        buildConfigField("String", "RELEASES_URL", "\"https://github.com/globulus/pacenote/releases/latest\"")
    }

    signingConfigs {
        if (signing.getProperty("storeFile") != null) {
            create("release") {
                storeFile = File(signingFile.parentFile, signing.getProperty("storeFile"))
                storePassword = signing.getProperty("storePassword")
                keyAlias = signing.getProperty("keyAlias")
                keyPassword = signing.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            buildConfigField("String", "DEFAULT_SERVICE_URL", "\"\"")
            buildConfigField("String", "DEFAULT_TOKEN", "\"\"")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        buildConfig = true
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

androidComponents {
    onVariants { variant ->
        val release = variant.buildType == "release"
        if (!release && (serviceToken.isEmpty() || serviceUrl.isEmpty())) {
            logger.warn("Pacenote: no service address or token in $pacenoteHome. Run scripts/setup.sh first, or pair in the app.")
        }
        val task = tasks.register<NetworkConfigTask>("write${variant.name.replaceFirstChar { it.uppercase() }}NetworkConfig") {
            host.set(if (release) "" else serviceHost)
        }
        variant.sources.res?.addGeneratedSourceDirectory(task, NetworkConfigTask::outputDir)
    }
}

